/**
 * Converts a Default Portfolio Item into a Project database seed format.
 */
export function defaultItemToProjectSeed(item: PortfolioItem): Partial<PortfolioProject> {
  return {
    source: "DEFAULT",
    legacyId: item.id,
    slug: item.id,
    title: item.title,
    category: item.category,
    domain: item.url.replace(/^https?:\/\//, "").replace(/\/.*$/, ""),
    imageUrl: item.image,
    externalUrl: item.url.startsWith("http") ? item.url : `https://${item.url}`,
    description: item.description || "",
    altText: `${item.title} — Web & SaaS Development Portfolio by Ekodrix`,
    isPublished: item.isPublished ?? true,
    isFeatured: item.isFeatured ?? false,
    isArchived: false,
    displayOrder: item.displayOrder ?? 0,
  };
}
